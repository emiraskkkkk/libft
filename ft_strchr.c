char	*ft_strchr(const char *s, int c)
{
	int		i;
	char	d;

	d = (char) c;
	i = 0;
	while (s[i] != '\0')
	{
		if (s[i] == d)
			return (&s[i]);
		i++;
	}
	if (d == '\0')
		return (&s[i]);
	return (0);
}
