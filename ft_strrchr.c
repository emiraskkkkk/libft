char	*ft_strrchr(const char *s, int c)
{
	int		i;
	char	d;

	i = 0;
	d = (char) c;
	while (s[i])
	{
		i++;
	}
	if (d == '\0')
		return (&s[i]);
	while (i >= 0)
	{
		if (s[i] == d)
			return (&s[i]);
		i--;
	}
	return (0);
}
